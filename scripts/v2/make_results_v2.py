"""Generate research/results_v2.md FROM the JSON/CSV outputs in results/v2 (no hand-typed numbers).
Run after all other v2 scripts: python scripts/v2/make_results_v2.py"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
T = ROOT / "results" / "v2" / "tables"
SEEN = "seen period (v1 reported it)"


def J(n):
    return json.load(open(T / n))


def ci(s, lo, hi):
    return f"{s:.2f} [{lo:.2f}, {hi:.2f}]"


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join("" if (isinstance(v, float) and pd.isna(v)) else str(v) for v in r) + " |")
    return "\n".join(out)


def verdict(b: bool) -> str:
    return "SUPPORTED" if b else "NOT SUPPORTED"


def main():
    ov, h1, h3 = J("overfit_audit.json"), J("h1_risk.json"), J("h3_hawkes.json")
    e1, e2, roll = J("e1_conformal.json"), J("e2_pysr.json"), J("roll_audit_sharpe.json")
    ex = pd.read_csv(T / "execution.csv")
    cap = pd.read_csv(T / "capacity.csv")
    sp = pd.read_csv(T / "seen_period.csv")
    rg = pd.read_csv(T / "roll_gaps.csv")
    cc = J("execution_contract_counts.json")
    adv = J("execution_adv_coverage.json")
    L = h1["literal"]
    h1_ok, h2_ok, h3_ok = h1["h1_supported_literal"], ov["H2"]["supported"], h3["blend"]["h3_supported"]
    pf = L["portfolio"]["2001-2017"]
    hm = h3["blend"]["multivariate"]
    fwd_path = ROOT / "results" / "v2" / "forward" / "forward.csv"
    fwd = pd.read_csv(fwd_path) if fwd_path.exists() else pd.DataFrame(columns=["date", "book", "net_return"])
    n_fwd = fwd["date"].nunique()
    parity = (ROOT.parent / "qengine" / "PARITY.md").read_text(encoding="utf-8")
    pm = re.search(r"corr\(run_weights, mbt\) = ([\d.]+); corr\(run_contracts, mbt\) = ([\d.]+)", parity)
    ps = re.search(r"Sharpe: mbt ([\d.\-]+), run_weights ([\d.\-]+), run_contracts ([\d.\-]+)", parity)
    o = []
    A = o.append
    A("# P7 v2 results: Riding Every Horizon, buy-side upgrade")
    A("")
    A("Generated by `scripts/v2/make_results_v2.py` from `results/v2/tables/*`. Pre-registration v2 hash "
      f"`{h1['prereg_hash']}` (never edited). Research artifact, not investment advice, not a live-trading instruction.")
    A("")
    A("**Timing.** Every signal is computed at the close of day t from data up to and including t. v1 trades at that "
      "close (`lag=1`); v2 also reports the realistic `lag=2` (trade at the next close). Choices used 2001-2017 data only.")
    A("")
    A("## Bottom line")
    A("")
    A(f"- H1 (GARCH tracks the risk target better than EWMA): **{verdict(h1_ok)}**.")
    A(f"- H2 (v1 is not an overfit pick: PBO < 0.5 and deflated Sharpe > 0.90): **{verdict(h2_ok)}**. "
      f"PBO {ov['pbo']:.3f} passes; deflated Sharpe {ov['v1_deflated_sharpe']:.3f} fails.")
    A(f"- H3 (crisis alpha follows crash clustering): **{verdict(h3_ok)}** (Newey-West t = "
      f"{hm['nw_t']['intensity']:.2f}, needs > 2).")
    A("- E1 (conformal filter) and E2 (PySR signal), both exploratory: no evidence of value.")
    A(f"- v1 blend, 2001-2017, v1 costs, lag 1: net Sharpe {ci(*roll['v1'])} over "
      f"{roll['n_days']} days. The interval includes zero, so v2 cannot claim the strategy has an edge in the choice period.")
    A("- v2 added nothing that beats v1. It added a tougher audit, a realistic cost and capacity picture, and an honest "
      "record of what did not work.")
    A("")
    A("## What survives")
    A("")
    cp = ov["cpcv"]
    A(f"- **Low PBO.** {ov['pbo']:.3f} over {ov['pbo_n_combinations']} CSCV combinations of {ov['n_trials']} configs: the config "
      "chosen in-sample rarely ranks below the median out-of-sample within 2001-2017. Caveat: this says selection is stable "
      "inside the family, not that the family has a real edge.")
    A(f"- **CPCV paths.** {cp['n_splits']} splits ({cp['n_groups']} groups, k_test {cp['k_test']}, embargo {cp['embargo']}d), "
      f"7 selection paths, annualised Sharpe {cp['min_path']:.2f} to {cp['max_path']:.2f}, median {cp['median_path_ann_sharpe']:.2f}. "
      "Selection almost always picks long-horizon configs. These are still 2001-2017 data, i.e. the choice period, so they are not unseen.")
    A(f"- **Costs realism.** The engine at lag 1 reproduces v1 exactly. Lag 2 changes net Sharpe little "
      f"({ex.iloc[1]['net_sharpe']:.2f} vs {ex.iloc[0]['net_sharpe']:.2f}); market impact is what bites (D1 below).")
    A("- **Capacity is small and data-limited.** See D1: capacity (Sharpe within 0.10 of the $10m value) is tens of "
      "millions of dollars under square-root impact at most, and Yahoo volume is too thin or wrong for several instruments, so the two ADV variants bracket the truth.")
    A(f"- **Roll-gap sensitivity is reported, not hidden.** {roll['n_flags_total']} flagged days; imputing them moves Sharpe by "
      f"{roll['delta']:.2f}, below the CI half-width {roll['ci_half_width_v1']:.2f}, so v1 data is kept.")
    A("")
    A("## Evidence ranking")
    A("")
    A("1. Forward paper tracking from 2026-11 (only unseen data). 2. CPCV / walk-forward on 2001-2017. "
      f"3. 2018-2026: {SEEN}; descriptive only.")
    A("")
    A("## Hypotheses (2001-2017 only)")
    A("")
    hyp = pd.DataFrame([
        ["H1 risk model", "EWMA RMSE minus GARCH RMSE > 0, 95% CI excludes 0",
         f"{L['h1_statistic_mean_rmse_ewma_minus_garch']:.3f} [{L['h1_ci95'][0]:.3f}, {L['h1_ci95'][1]:.3f}]", verdict(h1_ok)],
        ["H2 overfitting", "PBO < 0.5 and DSR > 0.90", f"PBO {ov['pbo']:.3f}; DSR {ov['v1_deflated_sharpe']:.3f}", verdict(h2_ok)],
        ["H3 crash clustering", "intensity coef > 0, NW t > 2",
         f"coef {hm['coef']['intensity']:.3f}, t {hm['nw_t']['intensity']:.2f}, n={hm['n_months']} months", verdict(h3_ok)],
    ], columns=["hypothesis", "rule (prereg)", "result", "verdict"])
    A(md(hyp))
    A("")
    g = h1["guarded_sensitivity"]
    A("### H1 detail")
    A("")
    A(f"- Literal rule fails because GARCH fits explode on a few instruments ({', '.join(L['worst_instruments_for_garch'])}). "
      f"GARCH is better on {L['n_instruments_garch_better']} of {L['n_instruments']} instruments (median RMSE gain {L['median_instrument_rmse_diff']:.4f}).")
    A(f"- Guarded variant (rejects bad fits; post-hoc sensitivity, not in the prereg): {g['h1_statistic_mean_rmse_ewma_minus_garch']:.3f} "
      f"[{g['h1_ci95'][0]:.3f}, {g['h1_ci95'][1]:.3f}], still not supported.")
    A(f"- Portfolio net Sharpe 2001-2017 (lag 1, v1 costs; {pf['n_days']} days; rebalance days EWMA {pf['ewma_rebalance_days']}, GARCH {pf['garch_rebalance_days']}): "
      f"EWMA {ci(*pf['ewma_sharpe_ci'])}; GARCH {ci(*pf['garch_sharpe_ci'])}; difference {pf['garch_minus_ewma']:.3f} "
      f"[{pf['diff_ci95'][0]:.3f}, {pf['diff_ci95'][1]:.3f}].")
    A("- 99% one-day VaR, 2004-2017 (secondary, fails): " + "; ".join(
        f"{k}: {x['breaches']} breaches of {x['n']} ({x['breach_rate']:.2%}), Kupiec p {x['kupiec_p']:.1e}, Christoffersen p {x['christoffersen_p']:.3f}"
        for k, x in L["var99"].items()) + ".")
    A("")
    A("### H2 detail")
    A("")
    A(f"- v1 blend Sharpe {ci(ov['v1_blend_ann_sharpe'], *ov['v1_blend_ci95'])}; expected maximum Sharpe of {ov['n_trials']} null trials "
      f"{ov['expected_max_sharpe_annualised']:.2f}; PSR vs 0 {ov['v1_psr_vs_0']:.3f}; best in-sample config `{ov['best_in_sample_config']}` "
      f"{ov['best_in_sample_ann_sharpe']:.2f}. {ov['n_configs_sharpe_gt_0']} of {ov['n_trials']} configs have Sharpe > 0.")
    A(f"- sr_var: {ov['sr_var_note']}. The configs are highly correlated, so a smaller effective trial count would raise the DSR; this was not applied.")
    b = ov["barbell_vs_blend"]
    A(f"- Barbell (21d + 252d) vs blend: {b['barbell_ann_sharpe']:.2f} [{b['barbell_ci95'][0]:.2f}, {b['barbell_ci95'][1]:.2f}]; "
      f"difference {b['diff_ann_sharpe_barbell_minus_blend']:.2f} [{b['diff_ci95'][0]:.2f}, {b['diff_ci95'][1]:.2f}] "
      f"({'CI excludes 0' if b['ci_excludes_zero'] else 'CI includes 0'}).")
    A("")
    A("### H3 detail")
    A("")
    hk, ev = h3["hawkes_full_sample"], h3["events"]
    hc = h3["hawkes_param_ci95_parametric_200_resims"]
    A(f"- {ev['n']} equity-crash events in {ev['n_days']} days ({ev['rule']}). Hawkes fit: mu {hk['mu']:.4f}/day, alpha {hk['alpha']:.3f}, "
      f"beta {hk['beta']:.3f}, branching ratio {hk['branching']:.3f} (parametric 95% CI [{hc['branching'][0]:.2f}, {hc['branching'][1]:.2f}]). "
      "Crashes cluster mildly; that part is real.")
    A(f"- The 20-event minimum makes the first usable month {h3['blend']['first_month']}, so n = {hm['n_months']} months, not the full 204. "
      f"Intensity has no detectable link to the next month's blend return (NW p = {hm['nw_p']['intensity']:.2f}).")
    A(f"- tick HawkesExpKern cross-check: {h3['tick_HawkesExpKern'].get('skipped', 'done')}.")
    A("")
    A("## D1 execution and capacity (2001-2017, v1 blend)")
    A("")
    prim = ex[ex["adv_variant"] == "primary_yahoo_adv"].copy()
    thin_ = ex[ex["adv_variant"] == "low_adv_instruments_impact_off"].copy()

    def tab(d):
        d = d.copy()
        d["net Sharpe [95% CI]"] = [ci(a, b_, c) for a, b_, c in zip(d.net_sharpe, d.ci95_lo, d.ci95_hi)]
        d["rebalance days"] = d.n_rebalance_days
        d["turnover/yr"] = d.turnover_per_yr.round(1)
        for c in ("ann_cost_linear", "ann_cost_roll", "ann_cost_impact"):
            d[c] = d[c].round(4)
        return d[["run", "net Sharpe [95% CI]", "ann_cost_linear", "ann_cost_roll", "ann_cost_impact", "turnover/yr", "rebalance days"]]

    A("Costs are annualised fractions of NAV. Lag 2 unless the row says lag1. Yahoo ADV (upper bound on impact):")
    A("")
    A(md(tab(prim[~prim["run"].str.startswith("contracts")])))
    A("")
    cont = prim[prim["run"].str.startswith("contracts")].copy()
    cont["net Sharpe [95% CI]"] = [ci(a, b_, c) for a, b_, c in zip(cont.net_sharpe, cont.ci95_lo, cont.ci95_hi)]
    A("Integer contracts (roll cost included, lag 2):")
    A("")
    A(md(cont[["run", "net Sharpe [95% CI]", "n_rebalance_days"]]))
    A("")
    A("Same impact rows with impact switched off for instruments whose Yahoo ADV is under $50m (lower bound on impact):")
    A("")
    A(md(tab(thin_[thin_["run"].str.contains("impact")])))
    A("")
    capt = cap.groupby(["adv_variant", "impact_coef"])["capacity_aum_drop0p10"].first().reset_index()
    capt["capacity AUM (USD)"] = capt["capacity_aum_drop0p10"].map(lambda x: f"{x:,.0f}")
    A("Capacity = largest AUM on the grid with net Sharpe within 0.10 of the $10m value:")
    A("")
    A(md(capt[["adv_variant", "impact_coef", "capacity AUM (USD)"]]))
    A("")
    A(f"Figure: `results/v2/figures/capacity.png`. Share of traded weight with no usable ADV (impact charged 0): {adv['share_traded_weight_without_adv']:.1%}.")
    if "2001-2017" in cc:
        lows = {k: sorted(c for c, x in v_.items() if x["median_abs_contracts"] <= 1) for k, v_ in cc["2001-2017"].items()}
        mins = {k: min(x["median_abs_contracts"] for x in v_.values()) for k, v_ in cc["2001-2017"].items()}
        A("Instruments with median |contracts| <= 1 while the target is on: " +
          "; ".join(f"AUM {k}: {len(l_)} (smallest median {mins[k]:.0f})" for k, l_ in lows.items()) + ".")
    A("")
    A("## D2 roll-gap sensitivity")
    A("")
    A(f"v1 blend {ci(*roll['v1'])} vs imputed {ci(*roll['imputed'])}; change {roll['delta']:.3f} vs CI half-width {roll['ci_half_width_v1']:.3f}; "
      f"decision: {'use imputed series' if roll['use_imputed_in_v2'] else 'keep v1 data, imputation is a sensitivity only'}. "
      "Top tickers by flags: " + ", ".join(f"{r.ticker} {int(r.n_flags)}" for r in rg.sort_values("n_flags", ascending=False).head(5).itertuples()) + ". "
      "Details, and the Yahoo FX volume defect, are in `research/data_audit_v2.md`.")
    A("")
    A("## E1 and E2 (EXPLORATORY, never headline)")
    A("")
    fb = e1["filter_book_2009_2017"]
    cv = e1["coverage_2009_2017"]
    A(f"- **E1 conformal.** Adaptive conformal intervals reach {cv['overall_weighted']:.3f} coverage vs {e1['coverage_target']:.2f} nominal "
      f"(CI [{cv['bootstrap_ci95_weekly_mean'][0]:.3f}, {cv['bootstrap_ci95_weekly_mean'][1]:.3f}]), so the intervals are calibrated. "
      f"The filter does not help: Sharpe {ci(*fb['filtered_sharpe_ci'])} vs base {ci(*fb['base_v1_lag2_sharpe_ci'])} "
      f"(2009-2017, lag 2, v1 costs, {fb['n_days']} days); difference {fb['diff_filtered_minus_base']:.3f} "
      f"[{fb['diff_ci95'][0]:.3f}, {fb['diff_ci95'][1]:.3f}]. The interval excludes zero on only {fb['mean_keep_share_full_position']:.1%} of instrument-days, "
      f"so it is nearly a 0.5x scaling (turnover/yr {fb['turnover_per_yr_base']:.0f} to {fb['turnover_per_yr_filtered']:.0f}).")
    pp = e2["portfolio_2013_2017_lag2_v1costs"]
    ic = e2["ic_2013_2017_weekly"]
    A(f"- **E2 PySR.** Best equation `{e2['chosen_equation_sympy']}` uses no trend feature. Judged once on 2013-2017: rank IC "
      f"{ic['eq']['mean_rank_ic']:.4f} (NW t {ic['eq']['t_newey_west_4']:.2f}) vs v1 "
      f"{ic['v1']['mean_rank_ic']:.4f} (t {ic['v1']['t_newey_west_4']:.2f}). Sharpe {ci(*pp['equation_sharpe_ci'])} vs v1 {ci(*pp['v1_signal_sharpe_ci'])} "
      f"({pp['n_days']} days; rebalance days {pp['rebalance_days_eq']} vs {pp['rebalance_days_v1']}); deflated Sharpe {e2['deflated_sharpe_chosen']:.2f} over {e2['n_pareto_equations']} equations. No evidence of value.")
    A("")
    A(f"## Seen period 2018-2026 - {SEEN}")
    A("")
    A("v1 already reported 2018-2026, so none of this is out-of-sample evidence. Lag 2. Impact rows use square-root impact coef 0.5 at AUM $100m. "
      "The 2001-2017 rows are the same books and execution for comparison.")
    A("")
    s = sp.copy()
    s["net Sharpe [95% CI]"] = [ci(a, b_, c) for a, b_, c in zip(s.net_sharpe, s.ci95_lo, s.ci95_hi)]
    s["ann ret"] = s.ann_return.map("{:.3f}".format)
    s["max DD"] = s.max_drawdown.map("{:.3f}".format)
    s["impact cost/yr"] = s.ann_cost_impact.map("{:.4f}".format)
    s["rebalance days"] = s.n_rebalance_days
    s["days"] = s.n_days
    A(md(s[["period", "book", "execution", "net Sharpe [95% CI]", "ann ret", "max DD", "impact cost/yr", "rebalance days", "days"]]))
    A("")
    A("Tearsheets (equity, drawdown, rolling Sharpe, monthly table, Monte Carlo, costs, assumptions): `results/v2/tearsheets/*.html`. "
      f"Files with `seen_2018_2026` in the name are the {SEEN}.")
    A("")
    A("## Forward test")
    A("")
    if n_fwd == 0:
        A("**0 days tracked.** The forward period starts 2026-11-01 and the data on disk ends before it. First read: 2027-11 (12 months). "
          "Run `python scripts/v2/forward.py --refresh` daily; it appends only new dates to `results/v2/forward/forward.csv`.")
    else:
        g2 = fwd.groupby("book")["net_return"].agg(["count", "mean", "std"])
        A(f"{n_fwd} days tracked. First read: 2027-11 (12 months). Do not read Sharpe before then.")
        A("")
        A(md(g2.reset_index()))
    A("")
    A("## ManifoldBT parity")
    A("")
    A("Before its licence ended, the qengine backtester was cross-checked against ManifoldBT 0.31.0 on the P7 v1 weights, 2001-2017 "
      "(parity diagnostics, not performance claims). Full tables and mismatches: [`qengine/PARITY.md`](../../qengine/PARITY.md); "
      "raw outputs in [`results/v2/manifoldbt/`](../results/v2/manifoldbt/).")
    if pm and ps:
        A("")
        A(f"Portfolio daily-return correlation with ManifoldBT: run_weights {pm.group(1)}, run_contracts {pm.group(2)}; "
          f"Sharpe mbt {ps.group(1)}, run_weights {ps.group(2)}, run_contracts {ps.group(3)}. "
          "The small gap is explained in PARITY.md (ManifoldBT freezes quantity between target changes, so weights drift with price; costs land one day earlier). "
          "A DSL version of the trend rule also ran through ManifoldBT, and its look-ahead check passed on the honest rule and failed on a deliberate lead.")
    A("")
    A("## Limitations")
    A("")
    A("- Yahoo `=F` series are not back-adjusted; Yahoo volume is unreliable for FX and several metals, so impact and capacity are bracketed, not pinned.")
    A("- Sharpe confidence intervals on 2001-2017 include zero; there is no demonstrated edge in the choice period.")
    A("- 2018-2026 is a seen period. Only the forward test can add unseen evidence.")
    A("- The DSR depends on the trial count and the cross-config Sharpe variance; both are judgment calls (stated above).")
    A("- No taxes, financing or short-borrow costs, and no slippage beyond the stated cost and impact model.")
    A("")
    (ROOT / "research" / "results_v2.md").write_text("\n".join(o) + "\n", encoding="utf-8")
    print("wrote research/results_v2.md", len(o), "lines")


if __name__ == "__main__":
    main()
